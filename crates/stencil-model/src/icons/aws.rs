    /// The file stem, for example "api-gateway".
    pub fn as_str(self) -> &'static str {
        let file_name = self.file_name();
        file_name.strip_suffix(".svg").unwrap_or(file_name)
    }

    /// The icon whose file stem is `stem`.
    pub fn from_stem(stem: &str) -> Option<AwsIcon> {
        AwsIcon::ALL.into_iter().find(|icon| icon.as_str() == stem)
    }
